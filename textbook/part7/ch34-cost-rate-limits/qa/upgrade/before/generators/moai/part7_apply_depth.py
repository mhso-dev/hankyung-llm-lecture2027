def html_block(first: str, second: str) -> str:
    def inline(text: str) -> str:
        parts = text.split("`")
        return "".join(f"<code>{part}</code>" if i % 2 else part for i, part in enumerate(parts))

    return f"<h3>코드 읽기와 개념 경계</h3><p>{inline(first)}</p><p>{inline(second)}</p>"


def notebook_cell(key: str, first: str, second: str) -> dict:
    chapter, lesson = key.split("/", 1)
    return {
        "cell_type": "markdown",
        "id": f"depth-{chapter[2:4]}-{lesson[:2]}",
        "metadata": {},
        "source": [
            "## 코드 읽기와 개념 경계\n",
            "\n",
            first + "\n",
            "\n",
            second,
        ],
    }


for key, (first, second) in LESSONS.items():
    chapter, lesson = key.split("/", 1)
    source_path = ROOT / "textbook/part7" / chapter / "_src" / f"{lesson}.html"
    text = source_path.read_text(encoding="utf-8")
    block = html_block(first, second)
    if "<h3>코드 읽기와 개념 경계</h3>" not in text:
        marker = "<h3>도식 읽기</h3>" if "<h3>도식 읽기</h3>" in text else '<h2 id="b5">'
        text = text.replace(marker, block + marker, 1)
        source_path.write_text(text, encoding="utf-8")

    notebook_path = ROOT / "labs/part7" / chapter / "notebooks" / f"{lesson}.ipynb"
    notebook = json.loads(notebook_path.read_text(encoding="utf-8"))
    depth_cells = [cell for cell in notebook["cells"] if cell.get("id", "").startswith("depth-")]
    if depth_cells:
        depth_cells[0]["id"] = notebook_cell(key, first, second)["id"]
    else:
        first_code = next(i for i, cell in enumerate(notebook["cells"]) if cell["cell_type"] == "code")
        notebook["cells"].insert(first_code, notebook_cell(key, first, second))
    notebook_path.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

