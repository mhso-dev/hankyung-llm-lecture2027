NEAREST = r'''# 값 목록을 작은 값부터 줄 세우고 가장 가까운 자리 방식으로 백분위수 하나를 찾습니다
def nearest_rank(values, percent):
    ordered = sorted(values)
    rank = math.ceil(percent * len(ordered) / 100)
    return ordered[rank - 1]'''

