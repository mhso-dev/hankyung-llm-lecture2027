DEF_STOP_LINE = r'''# 멈춘 까닭을 기록 한 줄로 만듭니다: 끝은 모델이 고른 멈춤, 나머지는 코드가 정한 멈춤
def stop_line(reason):
    chooser = "코드"
    if reason == "모델이 끝을 고름":
        chooser = "모델"
    return {"단계": "멈춤", "한 쪽": "코드", "고른 쪽": chooser, "결과": reason}'''

