DEF_SCORE = r'''# 답이 예인 질문의 가중치만 더해 워크플로우 점수를 냅니다
def workflow_score(questions, answers):
    score = 0
    for i in range(len(questions)):
        if answers[i] == "예":
            score = score + questions[i]["가중치"]
    return score'''

