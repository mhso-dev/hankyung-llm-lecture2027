def md_to_html(text: str) -> str:
    paragraphs = []
    for paragraph in text.split("\n\n"):
        escaped = html.escape(paragraph)
        escaped = re.sub(r"`([^`]+)`", r"<code>\1</code>", escaped)
        paragraphs.append(f"<p>{escaped}</p>")
    return "".join(paragraphs)


def update_html(path: Path, paragraphs: tuple[str, str]) -> None:
    source = path.read_text(encoding="utf-8")
    if "<h3>코드 읽기와 비교 경계</h3>" in source:
        return
    marker = "<h3>도식 읽기</h3>"
    if marker not in source:
        raise ValueError(f"도식 위치를 찾지 못했습니다: {path}")
    addition = "<h3>코드 읽기와 비교 경계</h3>" + "".join(md_to_html(p) for p in paragraphs)
    path.write_text(source.replace(marker, addition + marker, 1), encoding="utf-8")


def update_notebook(path: Path, paragraphs: tuple[str, str]) -> None:
    notebook = json.loads(path.read_text(encoding="utf-8"))
    candidates = [
        cell for index, cell in enumerate(notebook["cells"])
        if index >= 3 and cell.get("cell_type") == "markdown"
    ]
    if not candidates:
        raise ValueError(f"설명 셀을 찾지 못했습니다: {path}")
    cell = candidates[0]
    current = "".join(cell.get("source", []))
    if "### 코드 읽기와 비교 경계" in current:
        return
    addition = "\n\n### 코드 읽기와 비교 경계\n\n" + "\n\n".join(paragraphs) + "\n"
    updated = current.rstrip() + addition
    cell["source"] = updated.splitlines(keepends=True)
    path.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def digest_code_and_outputs(path: Path) -> str:
    notebook = json.loads(path.read_text(encoding="utf-8"))
    kept = [
        {"source": cell.get("source", []), "outputs": cell.get("outputs", [])}
        for cell in notebook["cells"] if cell.get("cell_type") == "code"
    ]
    payload = json.dumps(kept, ensure_ascii=False, sort_keys=True).encode()
    return hashlib.sha256(payload).hexdigest()


def main() -> None:
    changed = []
    for chapter in (25, 26, 27, 28, 29):
        html_dir = next((ROOT / "textbook/part6").glob(f"ch{chapter}-*/_src"))
        notebook_dir = next((ROOT / "labs/part6").glob(f"ch{chapter}-*/notebooks"))
        for html_path in sorted(html_dir.glob("*.html")):
            key = html_path.stem
            paragraphs = LESSONS[key]
            notebook_path = notebook_dir / f"{key}.ipynb"
            before_digest = digest_code_and_outputs(notebook_path)
            update_html(html_path, paragraphs)
            update_notebook(notebook_path, paragraphs)
            after_digest = digest_code_and_outputs(notebook_path)
            if before_digest != after_digest:
                raise AssertionError(f"코드 또는 출력이 바뀌었습니다: {notebook_path}")
            changed.append({"lesson": key, "code_output_sha256": after_digest})
    if set(LESSONS) != {item["lesson"] for item in changed}:
        raise AssertionError("개정 대상과 실제 처리 대상이 다릅니다")
    print(json.dumps({"lessons": len(changed), "items": changed}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
