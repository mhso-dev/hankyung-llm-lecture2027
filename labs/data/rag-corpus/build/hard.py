def png_data_uri(img: Image.Image) -> str:
    b = io.BytesIO(); img.save(b, format="PNG")
    return "data:image/png;base64," + base64.b64encode(b.getvalue()).decode()

def bar_chart(title, labels, values, unit="", w=900, h=460, color=(70, 110, 180)) -> str:
    """수치가 이미지 안에만 있는 막대 차트 (텍스트 레이어 없음)."""
    img = Image.new("RGB", (w, h), "white"); d = ImageDraw.Draw(img)
    f = ImageFont.truetype(FONT, 20); fb = ImageFont.truetype(FONT_B, 24); fs = ImageFont.truetype(FONT, 17)
    d.text((20, 12), title, fill="black", font=fb)
    top, bottom, left = 70, h - 60, 70
    mx = max(values) * 1.15
    d.line((left, top, left, bottom), fill="black", width=2); d.line((left, bottom, w - 20, bottom), fill="black", width=2)
    n = len(values); bw = (w - left - 40) / n * 0.6; gap = (w - left - 40) / n
    for i, (lab, v) in enumerate(zip(labels, values)):
        x0 = left + 20 + i * gap; y0 = bottom - (v / mx) * (bottom - top)
        d.rectangle((x0, y0, x0 + bw, bottom), fill=color)
        t = f"{v:,}{unit}"; tw = d.textlength(t, font=f)
        d.text((x0 + bw / 2 - tw / 2, y0 - 26), t, fill="black", font=f)
        lw = d.textlength(lab, font=fs); d.text((x0 + bw / 2 - lw / 2, bottom + 8), lab, fill="black", font=fs)
    return png_data_uri(img)

def line_chart(title, labels, series: dict, unit="", w=900, h=460) -> str:
    img = Image.new("RGB", (w, h), "white"); d = ImageDraw.Draw(img)
    f = ImageFont.truetype(FONT, 17); fb = ImageFont.truetype(FONT_B, 24)
    d.text((20, 12), title, fill="black", font=fb)
    top, bottom, left, right = 70, h - 60, 70, w - 30
    allv = [v for s in series.values() for v in s]; mx = max(allv) * 1.15; mn = 0
    d.line((left, top, left, bottom), fill="black", width=2); d.line((left, bottom, right, bottom), fill="black", width=2)
    n = len(labels); step = (right - left - 40) / (n - 1)
    cols = [(200, 60, 60), (60, 120, 200), (60, 160, 90)]
    for si, (name, vals) in enumerate(series.items()):
        pts = [(left + 20 + i * step, bottom - (v - mn) / (mx - mn) * (bottom - top)) for i, v in enumerate(vals)]
        d.line(pts, fill=cols[si], width=3)
        for (x, y), v in zip(pts, vals):
            d.ellipse((x - 4, y - 4, x + 4, y + 4), fill=cols[si]); d.text((x - 12, y - 24), f"{v}{unit}", fill=cols[si], font=f)
        d.rectangle((right - 200, top + si * 26, right - 180, top + si * 26 + 16), fill=cols[si]); d.text((right - 172, top + si * 26 - 3), name, fill="black", font=f)
    for i, lab in enumerate(labels):
        d.text((left + 20 + i * step - 20, bottom + 8), lab, fill="black", font=f)
    return png_data_uri(img)

